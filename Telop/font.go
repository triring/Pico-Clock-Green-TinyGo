// blankGlyph は、未対応文字を表示するときに使用する空白グリフです。
var blankGlyph Glyph

// glyphFor は、指定された文字に対応するグリフを返します。
// 辞書に登録されていない文字は空白として扱います。
func glyphFor(c byte) Glyph {
	glyph, ok := font[c]
	if !ok {
		return blankGlyph
	}
	return glyph
}
